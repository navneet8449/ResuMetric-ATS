import React, { useState } from 'react';
import { ATSAnalysisResult } from '../types';
import { X, Copy, Check, Download, FileText } from 'lucide-react';

interface ReportExportModalProps {
  result: ATSAnalysisResult;
  onClose: () => void;
}

export const ReportExportModal: React.FC<ReportExportModalProps> = ({ result, onClose }) => {
  const [copied, setCopied] = useState(false);

  const generateMarkdownReport = (): string => {
    const { candidateSummary, scoreBreakdown, technicalSkillsIdentified, missingSkillsGaps, jobComparison, suggestedImprovements } = result;

    return `# ATS Resume Analysis & Job Match Report
Generated by ResuMetric ATS

## 1. Candidate Overview
- **Candidate:** ${candidateSummary.detectedName || 'Candidate'}
- **Detected Title:** ${candidateSummary.detectedRoleOrTitle || 'N/A'}
- **Estimated Experience:** ${candidateSummary.totalYearsExperienceEstimated}
- **Target Role:** ${jobComparison.jobTitle || 'Target Role'}

### Executive Summary
${candidateSummary.executiveSummary}

### Honest ATS Recruiter Verdict
${candidateSummary.criticalHonestVerdict}

---

## 2. Match Score: ${scoreBreakdown.overallScore} / 100 (${scoreBreakdown.ratingTier})
- **Technical Skills:** ${scoreBreakdown.technicalSkillsScore.score}/${scoreBreakdown.technicalSkillsScore.max} - ${scoreBreakdown.technicalSkillsScore.rationale}
- **Seniority & Experience:** ${scoreBreakdown.experienceSeniorityScore.score}/${scoreBreakdown.experienceSeniorityScore.max} - ${scoreBreakdown.experienceSeniorityScore.rationale}
- **Keyword Density:** ${scoreBreakdown.keywordRequirementScore.score}/${scoreBreakdown.keywordRequirementScore.max} - ${scoreBreakdown.keywordRequirementScore.rationale}
- **ATS Parseability:** ${scoreBreakdown.atsFormattingScore.score}/${scoreBreakdown.atsFormattingScore.max} - ${scoreBreakdown.atsFormattingScore.rationale}

---

## 3. Technical Skills Identified
${technicalSkillsIdentified.map((cat) => `### ${cat.category}
${cat.skills.map((s) => `- **${s.name}** [${s.levelOfEvidence}]${s.contextQuoteOrNote ? `: ${s.contextQuoteOrNote}` : ''}`).join('\n')}`).join('\n\n')}

---

## 4. Missing Skills & Gaps
${missingSkillsGaps.map((gap) => `### ${gap.skill} (${gap.importance})
- **Why in JD:** ${gap.whyImportantInJD}
- **Recommendation:** ${gap.recommendation}`).join('\n\n')}

---

## 5. Suggested Improvements & Rewrites
${suggestedImprovements.map((imp) => `### ${imp.issue} (${imp.category})
- **Why it matters:** ${imp.explanationInSimpleEnglish}
${imp.beforeExample ? `- **Before:** ${imp.beforeExample}` : ''}
${imp.afterSuggestedRewrite ? `- **After:** ${imp.afterSuggestedRewrite}` : ''}`).join('\n\n')}

---
*Note: Never invent experience or skills. Genuine qualifications always win in technical interviews.*
`;
  };

  const reportText = generateMarkdownReport();

  const handleCopy = () => {
    navigator.clipboard.writeText(reportText);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const blob = new Blob([reportText], { type: 'text/markdown;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `ats-resume-analysis-${(result.candidateSummary.detectedName || 'candidate').toLowerCase().replace(/\s+/g, '-')}.md`;
    link.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 z-50 bg-slate-900/60 backdrop-blur-xs flex items-center justify-center p-4">
      <div className="bg-white dark:bg-slate-900 rounded-2xl border border-slate-200 dark:border-slate-800 shadow-xl max-w-3xl w-full max-h-[85vh] flex flex-col">
        {/* Header */}
        <div className="p-4 sm:p-5 border-b border-slate-200 dark:border-slate-800 flex items-center justify-between">
          <div className="flex items-center gap-2.5">
            <div className="w-8 h-8 rounded-lg bg-slate-100 dark:bg-slate-800 text-slate-700 dark:text-slate-300 flex items-center justify-center">
              <FileText className="w-4 h-4" />
            </div>
            <div>
              <h3 className="text-sm font-bold text-slate-900 dark:text-slate-100">
                Export ATS Analysis Report
              </h3>
              <p className="text-xs text-slate-500 dark:text-slate-400">
                Complete structured report ready for Markdown export or sharing
              </p>
            </div>
          </div>

          <button
            onClick={onClose}
            className="p-1.5 text-slate-400 hover:text-slate-600 dark:hover:text-slate-200 rounded-lg transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Content Preview */}
        <div className="p-4 sm:p-5 flex-1 overflow-y-auto">
          <textarea
            readOnly
            value={reportText}
            rows={16}
            className="w-full text-xs font-mono p-3.5 bg-slate-50 dark:bg-slate-950 border border-slate-200 dark:border-slate-800 rounded-lg text-slate-800 dark:text-slate-200 focus:outline-hidden resize-none"
          />
        </div>

        {/* Footer Actions */}
        <div className="p-4 border-t border-slate-200 dark:border-slate-800 flex items-center justify-between gap-3">
          <span className="text-xs text-slate-500 dark:text-slate-400">
            Format: Markdown (.md)
          </span>

          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="inline-flex items-center gap-1.5 px-3.5 py-2 text-xs font-semibold text-slate-700 dark:text-slate-200 bg-slate-100 hover:bg-slate-200 dark:bg-slate-800 dark:hover:bg-slate-700 rounded-lg transition-colors"
            >
              {copied ? (
                <>
                  <Check className="w-3.5 h-3.5 text-emerald-600" />
                  <span>Copied!</span>
                </>
              ) : (
                <>
                  <Copy className="w-3.5 h-3.5" />
                  <span>Copy Markdown</span>
                </>
              )}
            </button>

            <button
              onClick={handleDownload}
              className="inline-flex items-center gap-1.5 px-3.5 py-2 text-xs font-semibold text-white bg-slate-900 hover:bg-slate-800 dark:bg-emerald-600 dark:hover:bg-emerald-500 rounded-lg transition-colors"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download .md</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
